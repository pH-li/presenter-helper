// Writes public/config.js from environment variables (and .env locally).
// Netlify runs this as the build command; `npm start` runs it before serving.
//
// Only public values are allowed through: the Supabase project URL and the
// anon / publishable key. Secret keys make the build fail.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'public', 'config.js');

/** Minimal .env parser: KEY=value lines, # comments, optional quotes. */
export function parseEnv(text) {
  const env = {};
  for (const line of text.split(/\r?\n/)) {
    const m = line.match(/^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*?)\s*$/);
    if (!m) continue;
    let value = m[2];
    if (/^(['"]).*\1$/.test(value)) value = value.slice(1, -1);
    else value = value.replace(/\s+#.*$/, '');
    env[m[1]] = value;
  }
  return env;
}

/** Throws if the key is a secret / service-role key. */
export function assertPublicKey(key) {
  if (!key) return;
  if (key.startsWith('sb_secret_')) throw new Error('SUPABASE_ANON_KEY is a secret key (sb_secret_…). Use the publishable / anon key.');
  const parts = key.split('.');
  if (parts.length === 3) {
    let role;
    try {
      role = JSON.parse(Buffer.from(parts[1], 'base64url').toString('utf8')).role;
    } catch {
      return;
    }
    if (role === 'service_role') throw new Error('SUPABASE_ANON_KEY is the service_role key. Use the anon / publishable key.');
  }
}

/** Pick config from env, accepting the variable names Netlify's Supabase extension uses too. */
export function resolveConfig(env) {
  const url = [env.SUPABASE_URL, env.SUPABASE_DATABASE_URL].find((v) => v && /^https:\/\//.test(v)) || '';
  const key = env.SUPABASE_ANON_KEY || env.SUPABASE_PUBLISHABLE_KEY || '';
  assertPublicKey(key);
  return { supabaseUrl: url.replace(/\/+$/, ''), supabaseAnonKey: key };
}

function main() {
  const fileEnv = existsSync(join(ROOT, '.env')) ? parseEnv(readFileSync(join(ROOT, '.env'), 'utf8')) : {};
  const config = resolveConfig({ ...fileEnv, ...process.env });
  writeFileSync(
    OUT,
    `// Generated by scripts/write-config.js. Do not edit or commit.\nwindow.__APP_CONFIG__ = ${JSON.stringify(config, null, 2)};\n`
  );
  const enabled = config.supabaseUrl && config.supabaseAnonKey;
  console.log(enabled ? `config.js written: cloud sync ON (${config.supabaseUrl})` : 'config.js written: cloud sync OFF (no Supabase env vars)');
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    main();
  } catch (e) {
    console.error(`✗ ${e.message}`);
    process.exit(1);
  }
}
